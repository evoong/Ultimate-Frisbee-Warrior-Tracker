-- Request to join: the inverse of an invite. A signed-in user with no invite
-- asks a public team to let them in; a captain/editor approves or denies.
-- Like team_members and team_invites this is read-only to clients -- every
-- change goes through a security definer RPC that derives the caller from
-- auth.uid().
create table if not exists public.team_join_requests (
  id          bigint generated by default as identity primary key,
  team_id     bigint not null references public.organizations(id) on delete cascade,
  user_id     uuid   not null references auth.users(id) on delete cascade,
  -- Snapshot at request time: auth.users is not readable by a team manager
  -- and the requester is not on team_roster yet, so this is the only way to
  -- show who is asking.
  email       text   not null,
  created_at  timestamptz not null default now(),
  unique (team_id, user_id)
);

alter table public.team_join_requests enable row level security;
revoke all on public.team_join_requests from authenticated, anon;
grant select on public.team_join_requests to authenticated;

drop policy if exists "manager or requester read join requests" on public.team_join_requests;
create policy "manager or requester read join requests" on public.team_join_requests
  for select to authenticated
  using (
    user_id = (select auth.uid())
    or team_id = any ((select public.my_manage_team_ids())::bigint[])
  );

create or replace function public.request_to_join(p_team_id bigint)
returns bigint
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_uid   uuid;
  v_email text;
  v_id    bigint;
begin
  perform public.assert_not_guest();
  v_uid := (select auth.uid());

  -- Same rule as the public-teams browser: only public teams can be asked.
  -- A private team and a nonexistent one get the same message.
  if not (p_team_id = any (public.public_team_ids())) then
    raise exception 'no such public team';
  end if;
  if p_team_id = any (public.my_member_team_ids()) then
    raise exception 'you are already on this team';
  end if;

  select lower(u.email) into v_email
    from auth.users u where u.id = v_uid and u.email_confirmed_at is not null;
  if v_email is null then
    raise exception 'confirm your email address before requesting to join a team';
  end if;

  insert into public.team_join_requests (team_id, user_id, email)
  values (p_team_id, v_uid, v_email)
  on conflict (team_id, user_id) do update set email = excluded.email
  returning id into v_id;

  return v_id;
end;
$$;

create or replace function public.cancel_join_request(p_request_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
begin
  perform public.assert_not_guest();
  delete from public.team_join_requests
   where id = p_request_id and user_id = (select auth.uid());
end;
$$;

-- Approve and deny share the lookup + permission check. Unknown id and
-- other-team id collapse into one message so ids cannot be enumerated across
-- tenants (same reasoning as approve_claim).
create or replace function public.approve_join_request(p_request_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  r public.team_join_requests;
begin
  perform public.assert_not_guest();
  select * into r from public.team_join_requests where id = p_request_id;
  if r.id is null or not (r.team_id = any (public.my_manage_team_ids())) then
    raise exception 'no such request on your teams';
  end if;

  insert into public.team_members (team_id, user_id, role, invited_by)
  values (r.team_id, r.user_id, 'member', (select auth.uid()))
  on conflict (team_id, user_id) do nothing;

  delete from public.team_join_requests where id = r.id;
end;
$$;

create or replace function public.deny_join_request(p_request_id bigint)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  v_team_id bigint;
begin
  perform public.assert_not_guest();
  select team_id into v_team_id from public.team_join_requests where id = p_request_id;
  if v_team_id is null or not (v_team_id = any (public.my_manage_team_ids())) then
    raise exception 'no such request on your teams';
  end if;
  delete from public.team_join_requests where id = p_request_id;
end;
$$;

do $$
declare f text;
begin
  foreach f in array array[
    'public.request_to_join(bigint)',
    'public.cancel_join_request(bigint)',
    'public.approve_join_request(bigint)',
    'public.deny_join_request(bigint)'
  ]
  loop
    execute format('revoke all on function %s from public, anon', f);
    execute format('grant execute on function %s to authenticated', f);
  end loop;
end
$$;
